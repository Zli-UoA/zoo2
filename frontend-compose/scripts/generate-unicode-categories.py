"""Generate the portable Unicode 16 L/M/N table used by the channel validator.

Download https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt and pass
its local filename. The checksum pins the input; rebuilding the app needs no
Python or Unicode download. See composeResources/files/Unicode-LICENSE.txt.
"""
import hashlib
from pathlib import Path
import sys

raw = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(raw).hexdigest() == 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f'
ranges = []
start = None
for line in raw.decode().splitlines():
    fields = line.split(';')
    code, name, category = int(fields[0], 16), fields[1], fields[2]
    if category[0] not in 'LMN':
        continue
    if name.endswith(', First>'):
        start = code
        continue
    lo = start if name.endswith(', Last>') else code
    start = None
    if ranges and ranges[-1][1] + 1 == lo:
        ranges[-1] = (ranges[-1][0], code)
    else:
        ranges.append((lo, code))
output = Path(__file__).resolve().parents[1] / 'src/commonMain/kotlin/zoo/UnicodeCategories.kt'
header = '// Unicode 16.0 L/M/N categories. Generated by scripts/generate-unicode-categories.py.\n// Unicode License V3: composeResources/files/Unicode-LICENSE.txt\npackage zoo\n\nprivate val channelNameRanges = intArrayOf(\n'
body = ''.join(f'    0x{lo:x}, 0x{hi:x},\n' for lo, hi in ranges)
output.write_text(header + body + ''')

/** Match the backend's Unicode letter/mark/number policy, including non-BMP names. */
fun channelCharactersValid(value: String): Boolean {
    var at = 0
    while (at < value.length) {
        val ch = value[at++]
        val code = when {
            ch.isHighSurrogate() && at < value.length && value[at].isLowSurrogate() ->
                0x10000 + ((ch.code - 0xd800) shl 10) + (value[at++].code - 0xdc00)
            ch.isSurrogate() -> return false
            else -> ch.code
        }
        if (code == 45 || code == 95) continue
        var low = 0
        var high = channelNameRanges.size / 2 - 1
        var found = false
        while (low <= high) {
            val mid = (low + high) ushr 1
            when {
                code < channelNameRanges[mid * 2] -> high = mid - 1
                code > channelNameRanges[mid * 2 + 1] -> low = mid + 1
                else -> { found = true; break }
            }
        }
        if (!found) return false
    }
    return true
}
''')
