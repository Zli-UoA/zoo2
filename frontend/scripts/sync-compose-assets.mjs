const rows = [];
for (const name of names) {
  let file = new URL(`../node_modules/lucide-react/dist/esm/icons/${name}.mjs`, import.meta.url);
  let { __iconData: data } = await import(file);
  if (!data) {
    const source = await readFile(file, "utf8");
    file = new URL(source.match(/from ['"](.+?)['"]/)[1], file);
    ({ __iconData: data } = await import(file));
  }
  const paths = data.node.map(([tag, a]) => {
    if (tag === "path") return a.d;
    if (tag === "line") return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    if (tag === "polyline" || tag === "polygon")
      return `M${a.points}${tag === "polygon" ? "Z" : ""}`;
    if (tag === "circle")
      return `M${+a.cx - a.r} ${a.cy}a${a.r} ${a.r} 0 1 0 ${a.r * 2} 0a${a.r} ${a.r} 0 1 0 ${-a.r * 2} 0`;
    if (tag === "rect") {
      const x = +(a.x ?? 0),
        y = +(a.y ?? 0),
        w = +a.width,
        h = +a.height,
        r = +(a.rx ?? 0);
      return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${2 * r - w}a${r} ${r} 0 0 1 ${-r} ${-r}v${2 * r - h}a${r} ${r} 0 0 1 ${r} ${-r}Z`;
    }
    throw Error(`Unknown SVG shape: ${tag}`);
  });
  rows.push(
    `    ${JSON.stringify(name)} to listOf(${paths.map((p) => JSON.stringify(p)).join(", ")}),`,
  );
}
await writeFile(
  new URL("../../frontend-compose/src/commonMain/kotlin/zoo/IconData.kt", import.meta.url),
  `// Lucide geometry (ISC). Generated by frontend/scripts/sync-compose-assets.mjs.\npackage zoo\ninternal val iconPaths = mapOf(\n${rows.join("\n")}\n)\n`,
);
