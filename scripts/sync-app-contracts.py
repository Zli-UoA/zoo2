#!/usr/bin/env python3
"""Regenerate public event contracts from the checked-in official reference snapshot."""
import json,re
from pathlib import Path
root=Path(__file__).resolve().parent.parent
catalog=json.loads((root/'docs/slack-event-coverage.json').read_text())
native=[e['name'] for e in catalog['native_events']]
aliases=sorted({e['alias'] for e in catalog['aliases']})
mod=(root/'backend/src/apps/mod.rs').read_text()
scopes=re.findall(r'"([\w:]+)"',mod.split('pub const SCOPES:')[1].split('];',1)[0])
def write_json(path,value): (root/path).write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n')
schema=json.loads((root/'docs/app-events.schema.json').read_text())
event=schema['properties']['event']['properties'];event['type']['enum']=native;event['actor_id']['type']=['string','null'];event['subject_user_id']={'type':['string','null']}
write_json('docs/app-events.schema.json',schema)
api=json.loads((root/'docs/apps.openapi.json').read_text());manifest=api['components']['schemas']['Manifest']['properties']
manifest['scopes']['items']['enum']=scopes;manifest['events']['items']['enum']=native+aliases
manifest['functions']={'type':'array','maxItems':50,'uniqueItems':True,'items':{'type':'string'}}
manifest['user_connections']={'type':'boolean','default':False}
message=api['components']['schemas']['MessageInput']['properties'];message.update(kind={'type':'string','enum':['message','emote'],'default':'message'},broadcast={'type':'boolean','default':False},metadata={'type':['object','null']})
# Route handlers remain the source of paths and methods; retain handwritten request schemas.
for module in ['events','resources']:
 text=(root/f'backend/src/apps/{module}.rs').read_text()
 for match in re.finditer(r'\.route\(\s*"([^"]+)"\s*,',text):
  route=match.group(1);start=match.end();depth=1;end=start
  while depth:
   if text[end]=='(':depth+=1
   if text[end]==')':depth-=1
   end+=1
  methods=text[start:end-1]
  if not route.startswith('/api/'):continue
  verbs=re.findall(r'\b(get|post|patch|put|delete)\s*\(',methods)
  for verb in verbs:
   operation={'operationId':verb+'_'+re.sub(r'[^a-zA-Z0-9]+','_',route).strip('_'),'summary':verb.upper()+' '+route,'responses':{'200':{'description':'Success; see apps.md for resource fields and authorization.'},'400':{'description':'Invalid input'},'401':{'description':'Authentication required'},'403':{'description':'Insufficient scope or role'},'404':{'description':'Resource not visible'}}}
   if route!='/api/public-files/{token}' and not route.endswith('/events'): operation['security']=[{'appBearer':[]}] if route.startswith('/api/apps/v1/') else [{'humanBearer':[]}]
   params=[{'name':param,'in':'path','required':True,'schema':{'type':'string'}} for param in re.findall(r'\{(.*?)\}',route)]
   if params:operation['parameters']=params
   api['paths'].setdefault(route,{})[verb]=operation
write_json('docs/apps.openapi.json',api)
(root/'sdk/src/events.ts').write_text('// Generated by scripts/sync-app-contracts.py\nexport const EVENT_TYPES = '+json.dumps(native,indent=2)+' as const;\nexport type EventType = typeof EVENT_TYPES[number];\n')
lines=['# Slack イベント対応表','',f"参照: [{catalog['reference_url']}]({catalog['reference_url']})（{catalog['reference_date']} 時点）。",'',catalog['contract'],'','公式一覧 120 件のうち、91 件に対応する操作と発火元を実装し、5 件を通信プロトコルとして実装しています。24 件は下表の事情により対象外です。メッセージ subtype 33 件は別表に分類しています。','',
'発火元の統合テストは `backend/tests/app_event_sources_test.rs`、配信・OAuth・失効・ACK のテストは `backend/tests/apps_test.rs` にあります。DB の発火元があるだけでなく、公開 API の操作からイベントを確認します。ファイルのテストでは完了済みのオブジェクトストレージ状態を DB に準備し、実際の S3 転送は行いません。','',
'本人向けイベントは本人の有効な代理トークンと scope が必要です。配信の claim 時にも同意とチャンネル参加状態を確認します。`channel_joined` / `group_joined` / 対応する left は購読主体本人、`member_joined_channel` / `member_left_channel` は参加者変更全体です。','',
'| Slack event | Zoo event / 制御 | 状態・理由 |','| --- | --- | --- |']
for e in catalog['events']:
 target=', '.join('`'+n+'`' for n in e.get('zoo_events',[]))
 reason=e.get('reason','対応する操作から発火')
 lines.append(f"| [`{e['slack_event']}`]({e['source_url']}) | {target or '—'} | {reason} |")
lines+=['','## メッセージ subtype','','システム通知を重複したテキスト投稿にはせず、下表の構造化イベントとして配信します。','','| Slack subtype | Zoo event | 状態・理由 |','| --- | --- | --- |']
for e in catalog['message_subtypes']: lines.append('| `'+e['slack_subtype']+'` | '+', '.join('`'+n+'`' for n in e.get('zoo_events',[]))+' | '+e.get('reason','対応する操作から発火')+' |')
lines+=['','## Zoo のイベントと必要な権限','','`app` は操作先 App 限定、`self` は本人の同意が必要、`channel` は現在のチャンネル権限を適用します。公開チャンネルのメタデータは `channels:read` により発見できますが、メッセージ本文の読み取りには参加が必要です。','','| Zoo event | Scope | 配信先 |','| --- | --- | --- |']
for e in catalog['native_events']: lines.append(f"| `{e['name']}` | `{e['scope'] or '操作元の権限で検証'}` | {e['audience']} |")
(root/'docs/slack-event-coverage.md').write_text('\n'.join(lines)+'\n')
